#!/usr/bin/env node
/**
 * Build documentation/testing/TEST_REPORT.md from an executed run.
 *
 * Usage:
 *   node scripts/test-report.mjs run <outDir>     # runs every package's vitest suite with the JSON reporter
 *   node scripts/test-report.mjs write <outDir> [e2e-summary.json]
 *
 * The report only contains what the JSON files say. E2E results are passed in a small JSON file
 * ({ "suites": [{ "command": "...", "passed": n, "failed": n, "notes": "..." }] }) taken from the
 * Playwright output of the same run.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const ROOT = resolve(new URL('..', import.meta.url).pathname);
const PACKAGES = [
  'packages/validation',
  'packages/logging',
  'packages/ai',
  'packages/languages',
  'packages/syntax',
  'packages/sql',
  'packages/orm',
  'packages/scip',
  'packages/brain',
  'products/cvforge/core',
  'products/cvforge/backend',
  'products/cvforge/extension',
  'products/codeatlas/core',
  'products/codeatlas/service',
];

const [mode, outArg, e2eArg] = process.argv.slice(2);
if (!mode || !outArg) {
  console.error('usage: test-report.mjs run|write <outDir> [e2e-summary.json]');
  process.exit(2);
}
const outDir = resolve(outArg);

if (mode === 'run') {
  mkdirSync(outDir, { recursive: true });
  let failed = false;
  for (const pkg of PACKAGES) {
    const file = join(outDir, `${pkg.replaceAll('/', '__')}.json`);
    try {
      execFileSync('pnpm', ['exec', 'vitest', 'run', '--reporter=json', `--outputFile=${file}`], {
        cwd: join(ROOT, pkg),
        stdio: ['ignore', 'ignore', 'inherit'],
      });
    } catch {
      failed = true; // the JSON file still records which tests failed
    }
  }
  process.exit(failed ? 1 : 0);
}

if (mode !== 'write') {
  console.error(`unknown mode ${mode}`);
  process.exit(2);
}

const rows = [];
let total = 0;
let passed = 0;
let failedCount = 0;
let skipped = 0;
for (const f of readdirSync(outDir).filter((n) => n.endsWith('.json') && n.includes('__'))) {
  const pkg = f.replace(/\.json$/, '').replaceAll('__', '/');
  const r = JSON.parse(readFileSync(join(outDir, f), 'utf8'));
  total += r.numTotalTests;
  passed += r.numPassedTests;
  failedCount += r.numFailedTests;
  skipped += r.numPendingTests + (r.numTodoTests ?? 0);
  for (const t of r.testResults) {
    const assertions = t.assertionResults;
    rows.push({
      pkg,
      file: relative(join(ROOT, pkg), t.name),
      tests: assertions.length,
      passed: assertions.filter((a) => a.status === 'passed').length,
      failed: assertions.filter((a) => a.status === 'failed').map((a) => a.fullName),
      ms: Math.round((t.endTime ?? 0) - (t.startTime ?? 0)),
    });
  }
}
rows.sort((a, b) => a.pkg.localeCompare(b.pkg) || a.file.localeCompare(b.file));
const e2e = e2eArg && existsSync(e2eArg) ? JSON.parse(readFileSync(e2eArg, 'utf8')) : null;
const node = process.version;
const date = new Date().toISOString().slice(0, 10);

const lines = [
  '# Test report',
  '',
  `Generated by \`node scripts/test-report.mjs\` on ${date} from an executed run (Node ${node}). Do not edit by hand; re-run the script.`,
  '',
  '## Summary',
  '',
  '| Suite | Tests | Passed | Failed | Skipped |',
  '| ----- | ----: | -----: | -----: | ------: |',
  `| Unit and integration (vitest, ${PACKAGES.length} packages) | ${total} | ${passed} | ${failedCount} | ${skipped} |`,
];
for (const s of e2e?.suites ?? [])
  lines.push(`| E2E: \`${s.command}\` | ${s.passed + s.failed} | ${s.passed} | ${s.failed} | 0 |`);
lines.push(
  '',
  '## Unit and integration tests by file',
  '',
  '| Package | File | Tests | Passed | Duration |',
  '| ------- | ---- | ----: | -----: | -------: |',
);
for (const r of rows)
  lines.push(`| ${r.pkg} | \`${r.file}\` | ${r.tests} | ${r.passed} | ${r.ms} ms |`);
const failures = rows.flatMap((r) => r.failed.map((name) => `- ${r.pkg} \`${r.file}\`: ${name}`));
lines.push('', '## Failures', '', failures.length ? failures.join('\n') : 'None.');
if (e2e) {
  lines.push('', '## End-to-end suites', '');
  for (const s of e2e.suites)
    lines.push(
      `- \`${s.command}\`: ${s.passed} passed, ${s.failed} failed. ${s.notes ?? ''}`.trimEnd(),
    );
}
if (e2e?.other?.length) {
  lines.push('', '## Other checks in the same run', '');
  for (const o of e2e.other) lines.push(`- \`${o.command}\`: ${o.result}`);
}
lines.push(
  '',
  '## Not covered by this run',
  '',
  '- Live LinkedIn and Naukri pages (manual checklist in RELEASE_READINESS.md).',
  '- Real model quality: AI paths are tested with fake providers only.',
  '- Manual accessibility audit: only automated axe rules ran.',
  '',
);
mkdirSync(join(ROOT, 'documentation/testing'), { recursive: true });
writeFileSync(join(ROOT, 'documentation/testing/TEST_REPORT.md'), lines.join('\n'));
console.log(`wrote TEST_REPORT.md: ${total} tests, ${failedCount} failed`);
