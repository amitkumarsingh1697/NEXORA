// Bundles the CodeAtlas brain command into the ArchLens skill (ADR 0020):
//   skills/archlens/scripts/brain/brain.mjs      the indexer, one ES module (esbuild)
//   skills/archlens/scripts/brain/*.wasm         web-tree-sitter and libpg-query runtimes
//   skills/archlens/scripts/brain/lib.*.d.ts     TypeScript's standard library declarations
//   skills/archlens/scripts/brain/grammars/      the tree-sitter grammars with their manifest
// The result needs Node.js 22.5 or later (node:sqlite) and nothing else.
// Run: pnpm --filter @nexora/codeatlas-service skill
import { build } from 'esbuild';
import { cpSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..', '..');
const out = process.env.ARCHLENS_BRAIN_OUT ?? join(root, 'skills', 'archlens', 'scripts', 'brain');
const req = createRequire(join(root, 'packages', 'syntax', 'package.json'));
const sqlReq = createRequire(join(root, 'packages', 'sql', 'package.json'));
const ormReq = createRequire(join(root, 'packages', 'orm', 'package.json'));

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
await build({
  entryPoints: [join(here, '..', 'src', 'skill-brain.ts')],
  outfile: join(out, 'brain.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  minify: true,
  legalComments: 'eof',
  // CommonJS dependencies (TypeScript, the PostgreSQL parser) expect these names; they point at
  // this folder, where the .wasm runtimes and TypeScript's lib files are copied below.
  banner: {
    js: [
      '// Generated by `pnpm --filter @nexora/codeatlas-service skill` from products/codeatlas (ADR 0020). Do not edit.',
      "import{createRequire as __cr}from'node:module';import{fileURLToPath as __fu}from'node:url';import{dirname as __dn}from'node:path';",
      'const require=__cr(import.meta.url);const __filename=__fu(import.meta.url);const __dirname=__dn(__filename);',
    ].join('\n'),
  },
  logLevel: 'warning',
});
cpSync(join(root, 'packages', 'syntax', 'grammars'), join(out, 'grammars'), { recursive: true });
cpSync(req.resolve('web-tree-sitter/web-tree-sitter.wasm'), join(out, 'web-tree-sitter.wasm'));
cpSync(
  join(dirname(sqlReq.resolve('libpg-query/package.json')), 'wasm', 'libpg-query.wasm'),
  join(out, 'libpg-query.wasm'),
);
const tsLib = join(dirname(ormReq.resolve('typescript/package.json')), 'lib');
for (const f of readdirSync(tsLib))
  if (/^lib\..*\.d\.ts$/.test(f)) cpSync(join(tsLib, f), join(out, f));
cpSync(join(tsLib, '..', 'LICENSE.txt'), join(out, 'TYPESCRIPT-LICENSE.txt'));
writeFileSync(
  join(out, 'README.md'),
  '# brain\n\nGenerated by `pnpm --filter @nexora/codeatlas-service skill` (ADR 0020). Do not edit.\n\n' +
    '`node brain.mjs <repo> [--out file.html] [--json model.json] [--scip x.scip]… [--run-indexers]` indexes a repository with the CodeAtlas indexer and writes its architecture brain. Needs Node.js 22.5 or later.\n\n' +
    'Third-party code in `brain.mjs` keeps its licence comments at the end of the file. TypeScript (Apache-2.0): `TYPESCRIPT-LICENSE.txt`. Grammars: `grammars/MANIFEST.json` and `grammars/*.LICENSE`.\n',
);
let bytes = 0;
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    const s = statSync(p);
    if (s.isDirectory()) walk(p);
    else bytes += s.size;
  }
};
walk(out);
console.log(`skills/archlens/scripts/brain: ${(bytes / 1048576).toFixed(1)} MiB`);
