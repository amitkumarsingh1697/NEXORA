// Bundles the CodeAtlas brain command into the ArchLens skill (ADR 0020):
//   skills/archlens/scripts/brain/brain.mjs           the indexer, one ES module (esbuild)
//   skills/archlens/scripts/brain/web-tree-sitter.wasm the tree-sitter runtime
//   skills/archlens/scripts/brain/runtime.pack.gz     TypeScript's lib.*.d.ts, the tree-sitter
//                                                     grammars and the libpg-query runtime, in one
//                                                     file: claude.ai accepts skills of at most
//                                                     200 files. brain.mjs unpacks it into a new
//                                                     temporary folder on each run and removes it.
//   skills/archlens/scripts/brain/GRAMMARS.json, GRAMMAR-LICENSES.txt  manifest and licences
// The result needs Node.js 22.5 or later (node:sqlite) and nothing else.
// Run: pnpm --filter @nexora/codeatlas-service skill
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import {
  cpSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..', '..');
const out = process.env.ARCHLENS_BRAIN_OUT ?? join(root, 'skills', 'archlens', 'scripts', 'brain');
const req = createRequire(join(root, 'packages', 'syntax', 'package.json'));
const sqlReq = createRequire(join(root, 'packages', 'sql', 'package.json'));
const ormReq = createRequire(join(root, 'packages', 'orm', 'package.json'));

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
await build({
  entryPoints: [join(here, '..', 'src', 'skill-brain.ts')],
  outfile: join(out, 'brain.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  minify: true,
  legalComments: 'eof',
  // CommonJS dependencies (TypeScript, the PostgreSQL parser) find their files next to
  // __filename; it points into a fresh temporary folder where runtime.pack.gz is unpacked
  // (one folder per process, removed on exit, so nothing is shared between users or runs).
  banner: {
    js: [
      '// Generated by `pnpm --filter @nexora/codeatlas-service skill` from products/codeatlas (ADR 0020). Do not edit.',
      "import{createRequire as __cr}from'node:module';import{fileURLToPath as __fu}from'node:url';import{dirname as __dn,join as __jn}from'node:path';import{mkdtempSync as __mk,mkdirSync as __md,readFileSync as __rf,writeFileSync as __wf,rmSync as __rm}from'node:fs';import{tmpdir as __td}from'node:os';import{gunzipSync as __gz}from'node:zlib';",
      'const require=__cr(import.meta.url);',
      "const __rt=(()=>{const h=__dn(__fu(import.meta.url)),d=__mk(__jn(__td(),'archlens-brain-'));process.on('exit',()=>__rm(d,{recursive:true,force:true}));const b=__gz(__rf(__jn(h,'runtime.pack.gz'))),n=b.readUInt32LE(0);let o=4+n;for(const[f,s]of JSON.parse(b.subarray(4,o).toString())){const p=__jn(d,f);__md(__dn(p),{recursive:true});__wf(p,b.subarray(o,o+s));o+=s}return d})();",
      "globalThis.__ARCHLENS_RUNTIME__=__rt;const __filename=__jn(__rt,'brain.mjs');const __dirname=__rt;",
    ].join('\n'),
  },
  logLevel: 'warning',
});
// web-tree-sitter finds its runtime next to the module (import.meta.url), so it stays a file.
cpSync(req.resolve('web-tree-sitter/web-tree-sitter.wasm'), join(out, 'web-tree-sitter.wasm'));
// Everything else goes into one pack: [u32 index length][JSON [[name, size]…]][bytes…], gzipped.
const grammarDir = join(root, 'packages', 'syntax', 'grammars');
const tsLib = join(dirname(ormReq.resolve('typescript/package.json')), 'lib');
const entries = [
  ...readdirSync(tsLib)
    .filter((f) => /^lib\..*\.d\.ts$/.test(f))
    .sort()
    .map((f) => [f, join(tsLib, f)]),
  ...readdirSync(grammarDir)
    .filter((f) => /\.wasm\.gz$|^MANIFEST\.json$/.test(f))
    .sort()
    .map((f) => [`grammars/${f}`, join(grammarDir, f)]),
  [
    'libpg-query.wasm',
    join(dirname(sqlReq.resolve('libpg-query/package.json')), 'wasm', 'libpg-query.wasm'),
  ],
];
const bodies = entries.map(([, p]) => readFileSync(p));
const index = Buffer.from(JSON.stringify(entries.map(([n], i) => [n, bodies[i].length])));
const head = Buffer.alloc(4);
head.writeUInt32LE(index.length, 0);
writeFileSync(
  join(out, 'runtime.pack.gz'),
  gzipSync(Buffer.concat([head, index, ...bodies]), { level: 9 }),
);
cpSync(join(grammarDir, 'MANIFEST.json'), join(out, 'GRAMMARS.json'));
writeFileSync(
  join(out, 'GRAMMAR-LICENSES.txt'),
  readdirSync(grammarDir)
    .filter((f) => f.endsWith('.LICENSE'))
    .sort()
    .map(
      (f) =>
        `==== ${f.replace(/\.LICENSE$/, '')} ====\n\n${readFileSync(join(grammarDir, f), 'utf8').trim()}\n`,
    )
    .join('\n'),
);
cpSync(join(tsLib, '..', 'LICENSE.txt'), join(out, 'TYPESCRIPT-LICENSE.txt'));
const packHash = createHash('sha256')
  .update(readFileSync(join(out, 'runtime.pack.gz')))
  .digest('hex');
writeFileSync(
  join(out, 'README.md'),
  '# brain\n\nGenerated by `pnpm --filter @nexora/codeatlas-service skill` (ADR 0020). Do not edit.\n\n' +
    '`node brain.mjs <repo> [--out file.html] [--json model.json] [--scip x.scip]… [--run-indexers]` indexes a repository with the CodeAtlas indexer and writes its architecture brain. Needs Node.js 22.5 or later.\n\n' +
    'Third-party code in `brain.mjs` keeps its licence comments at the end of the file. TypeScript (Apache-2.0): `TYPESCRIPT-LICENSE.txt`. Grammars: `GRAMMARS.json` (sources and commits) and `GRAMMAR-LICENSES.txt`.\n\n' +
    "`runtime.pack.gz` holds TypeScript's `lib.*.d.ts` files, the tree-sitter grammars and the libpg-query runtime in one file, because claude.ai accepts skills of at most 200 files. `brain.mjs` unpacks it into a new temporary folder on each run and removes the folder when it exits. " +
    `Its SHA-256 is ${packHash}.\n`,
);
let bytes = 0;
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    const s = statSync(p);
    if (s.isDirectory()) walk(p);
    else bytes += s.size;
  }
};
walk(out);
console.log(`skills/archlens/scripts/brain: ${(bytes / 1048576).toFixed(1)} MiB`);
